from __future__ import annotations
from pathlib import Path
import base64
import io
import pandas as pd
import matplotlib.pyplot as plt


def _save_fig(fig, path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


def generate_eda_report(df: pd.DataFrame, out_dir: Path) -> Path:
    """Generate a lightweight HTML EDA report after cleaning.
    This avoids extra heavy dependencies (like pandas-profiling) and is deterministic.
    """
    out_dir.mkdir(parents=True, exist_ok=True)

    # Basic info
    n_rows, n_cols = df.shape
    missing = df.isna().sum().sort_values(ascending=False)
    missing = missing[missing > 0]

    # Summary tables
    numeric_desc = df.select_dtypes(include="number").describe().T
    cat_desc = df.select_dtypes(exclude="number").describe(include="all").T

    # Plots
    plots = []

    # Churn distribution
    if "Churn" in df.columns:
        fig = plt.figure()
        df["Churn"].value_counts().plot(kind="bar")
        plt.title("Churn Distribution (0=No, 1=Yes)")
        p = out_dir / "churn_distribution.png"
        _save_fig(fig, p)
        plots.append(("Churn Distribution", p.name))

    # Numeric histograms
    num_cols = df.select_dtypes(include="number").columns.tolist()
    for col in num_cols[:8]:  # keep report light
        fig = plt.figure()
        df[col].dropna().hist(bins=30)
        plt.title(f"Histogram: {col}")
        p = out_dir / f"hist_{col}.png"
        _save_fig(fig, p)
        plots.append((f"Histogram: {col}", p.name))

    # Correlation (numeric)
    if len(num_cols) >= 2:
        corr = df[num_cols].corr(numeric_only=True)
        fig = plt.figure(figsize=(8, 6))
        plt.imshow(corr.values)
        plt.title("Correlation Matrix (numeric)")
        plt.xticks(range(len(num_cols)), num_cols, rotation=45, ha="right")
        plt.yticks(range(len(num_cols)), num_cols)
        plt.colorbar()
        p = out_dir / "correlation_matrix.png"
        _save_fig(fig, p)
        plots.append(("Correlation Matrix (numeric)", p.name))

    # Build HTML
    def df_to_html(dfx: pd.DataFrame, max_rows=30):
        if dfx is None or dfx.empty:
            return "<p><em>None</em></p>"
        return dfx.head(max_rows).to_html(border=1)

    missing_html = missing.to_frame("missing_count").to_html(border=1) if not missing.empty else "<p><em>No missing values after cleaning.</em></p>"

    plots_html = ""
    for title, fname in plots:
        plots_html += f"<h3>{title}</h3><img src='{fname}' style='max-width: 100%; height: auto; border:1px solid #ddd; padding:4px;'/>\n"

    html = f"""<!doctype html>
<html>
<head>
  <meta charset="utf-8"/>
  <title>Telco Churn ƒ?" EDA Report</title>
  <style>
    body {{ font-family: Arial, sans-serif; margin: 24px; }}
    code {{ background:#f3f3f3; padding:2px 4px; }}
    table {{ border-collapse: collapse; }}
    th, td {{ padding: 6px 8px; }}
    th {{ background: #f7f7f7; }}
  </style>
</head>
<body>
  <h1>EDA Report (After Cleaning)</h1>
  <p><b>Rows:</b> {n_rows} &nbsp;&nbsp; <b>Columns:</b> {n_cols}</p>

  <h2>Missing Values</h2>
  {missing_html}

  <h2>Numeric Summary</h2>
  {df_to_html(numeric_desc)}

  <h2>Categorical Summary</h2>
  {df_to_html(cat_desc)}

  <h2>Plots</h2>
  {plots_html}

  <hr/>
  <p style="color:#777;">Generated by backend/ml/eda.py</p>
</body>
</html>"""

    report_path = out_dir / "eda_report.html"
    report_path.write_text(html, encoding="utf-8")
    return report_path
